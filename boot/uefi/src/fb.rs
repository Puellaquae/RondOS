//! Minimal framebuffer text console for the UEFI loader stage.
//!
//! After setting a GOP graphics mode, the firmware's `SimpleTextOutput`
//! protocol is no longer visible on screen.  This module renders 8×16
//! bitmap text directly to the linear framebuffer so boot progress is
//! observable on the display.
//!
//! The console mirrors the kernel's `io/fb.rs` but is simplified: no
//! scrolling (the loader uses far fewer than 60 lines), no device-window
//! mapping (the loader's page tables identity-map the framebuffer), and
//! no serial backup (the loader runs before the kernel's serial driver).

use core::cell::UnsafeCell;

