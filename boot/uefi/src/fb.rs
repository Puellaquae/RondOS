const MAX_COLS: usize = 120;
const MAX_ROWS: usize = 60;

const COLOR_FG: u32 = 0x00C0_C0C0; // light grey on ...
const COLOR_BG: u32 = 0x0080_8080; // ... mid-grey

struct Console {
    ready: bool,
    base: *mut u8,
    width: u32,
    height: u32,
    pitch: u32,
    format: u8, // 1 = BGRx, 2 = RGBx
    cols: u32,
    rows: u32,
    cx: u32,
    cy: u32,
    text: [[u8; MAX_COLS]; MAX_ROWS],
}

impl Console {
    const fn new() -> Self {
        Self {
            ready: false,
            base: core::ptr::null_mut(),
            width: 0,
            height: 0,
            pitch: 0,
            format: 1,
            cols: 0,
            rows: 0,
            cx: 0,
            cy: 0,
            text: [[b' '; MAX_COLS]; MAX_ROWS],
        }
    }
}

#[repr(transparent)]
struct ConsoleCell(UnsafeCell<Console>);

unsafe impl Sync for ConsoleCell {}

static CONSOLE: ConsoleCell = ConsoleCell(UnsafeCell::new(Console::new()));

fn con() -> &'static mut Console {
    unsafe { &mut *CONSOLE.0.get() }
}

/// Initialise the console from the GOP framebuffer parameters.
pub fn init(base: u64, width: u32, height: u32, pitch: u32, format: u8) {
    let c = con();
    c.base = base as *mut u8;
    c.width = width;
    c.height = height;
    c.pitch = pitch;
    c.format = format;
    c.cols = (width / FONT_WIDTH as u32).min(MAX_COLS as u32);
    c.rows = (height / FONT_HEIGHT as u32).min(MAX_ROWS as u32);
    c.ready = c.cols > 0 && c.rows > 0;
    c.cx = 0;
    c.cy = 0;
    c.text = [[b' '; MAX_COLS]; MAX_ROWS];
    if c.ready {
        clear();
    }
}

#[inline]
fn pack(c: &Console, rgb: u32) -> u32 {
    let (r, g, b) = ((rgb >> 16) & 0xff, (rgb >> 8) & 0xff, rgb & 0xff);
    match c.format {
        2 => (b << 16) | (g << 8) | r, // RGBx: memory order R,G,B,X
        _ => (r << 16) | (g << 8) | b, // BGRx: memory order B,G,R,X
    }
}

#[inline]
unsafe fn put_pixel(c: &Console, x: u32, y: u32, rgb: u32) {
    if x >= c.width || y >= c.height {
        return;
    }
    let p = c.base.add((y * c.pitch + x * 4) as usize);
    core::ptr::write_volatile(p as *mut u32, pack(c, rgb));
}

unsafe fn fill_rect(c: &Console, x: u32, y: u32, w: u32, h: u32, rgb: u32) {
    for yy in y..(y + h).min(c.height) {
        for xx in x..(x + w).min(c.width) {
            put_pixel(c, xx, yy, rgb);
        }
    }
}

unsafe fn draw_cell(c: &Console, col: u32, row: u32, ch: u8, fg: u32, bg: u32) {
    let x0 = col * FONT_WIDTH as u32;
    let y0 = row * FONT_HEIGHT as u32;
    let idx = if (FONT_FIRST..=FONT_LAST).contains(&(ch as usize)) {
        ch as usize - FONT_FIRST
    } else {
        b'?' as usize - FONT_FIRST
    };
    let glyph = &FONT[idx];
    for (dy, bits) in glyph.iter().enumerate() {
        for dx in 0..FONT_WIDTH as u32 {
            let on = (*bits >> (7 - dx)) & 1 != 0;
            put_pixel(c, x0 + dx, y0 + dy as u32, if on { fg } else { bg });
        }
    }
}

pub fn clear() {
    let c = con();
    if !c.ready {
        return;
    }
    unsafe { fill_rect(c, 0, 0, c.width, c.height, COLOR_BG) };
    for row in c.text.iter_mut() {
        for cell in row.iter_mut() {
            *cell = b' ';
        }
    }
    c.cx = 0;
    c.cy = 0;
}

fn newline() {
    let c = con();
    if !c.ready {
        return;
    }
    c.cx = 0;
    if c.cy + 1 >= c.rows {
        c.cy = c.rows - 1;
        unsafe {
            let total_rows = c.rows * FONT_HEIGHT as u32;
            let fy = FONT_HEIGHT as u32;
            for y in fy..total_rows {
                let src = c.base.add(y as usize * c.pitch as usize);
                let dst = c.base.add((y - fy) as usize * c.pitch as usize);
                core::ptr::copy_nonoverlapping(src, dst, c.pitch as usize);
            }
            fill_rect(
                c,
                0,
                (c.rows - 1) * FONT_HEIGHT as u32,
                c.width,
                FONT_HEIGHT as u32,
                COLOR_BG,
            );
        }
        for row in 0..(c.rows as usize - 1) {
            c.text[row] = c.text[row + 1];
        }
        let last = c.rows as usize - 1;
        for cell in c.text[last].iter_mut() {
            *cell = b' ';
        }
    } else {
        c.cy += 1;
    }
}

fn put_char(ch: u8) {
    let c = con();
    if !c.ready {
        return;
    }
    match ch {
        b'\n' => newline(),
        b'\r' => c.cx = 0,
        b'\t' => {
            let next = (c.cx / 8 + 1) * 8;
            while c.cx < next && c.cx < c.cols {
                let (cx, cy) = (c.cx as usize, c.cy as usize);
                c.text[cy][cx] = b' ';
                unsafe { draw_cell(c, c.cx, c.cy, b' ', COLOR_FG, COLOR_BG) };
                c.cx += 1;
            }
        }
        b'\x08' => {
            if c.cx > 0 {
                c.cx -= 1;
            }
            let (cx, cy) = (c.cx as usize, c.cy as usize);
            c.text[cy][cx] = b' ';
            unsafe { draw_cell(c, c.cx, c.cy, b' ', COLOR_FG, COLOR_BG) };
        }
        _ => {
            if c.cx >= c.cols {
                newline();
            }
            let (cx, cy) = (c.cx as usize, c.cy as usize);
            c.text[cy][cx] = ch;
            unsafe { draw_cell(c, c.cx, c.cy, ch, COLOR_FG, COLOR_BG) };
            c.cx += 1;
            if c.cx >= c.cols {
                newline();
            }
        }
    }
}

/// Write raw bytes to the framebuffer console.
pub fn write(bytes: &[u8]) {
    if !con().ready {
        return;
    }
    for &b in bytes {
        put_char(b);
    }
}

/// `core::fmt::Write` adapter so `writeln!`/`write!` can be used on the
/// framebuffer console.
pub struct Writer;

impl core::fmt::Write for Writer {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        write(s.as_bytes());
        Ok(())
    }
}
